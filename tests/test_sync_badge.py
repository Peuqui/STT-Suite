"""The sync script that hands the dictation button of ui/badge/ to the programs (scripts/sync_badge.py)."""
import json
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "scripts"))
import sync_badge

REAL_SVG = (sync_badge.SOURCE / "badge.svg").read_text(encoding="utf-8")
KEYS_PER_KIND = {
    "source": {"name", "kind", "repo", "uses", "speech"},
    "vue": {"name", "kind", "repo", "uses", "speech", "css", "component"},
    "html": {"name", "kind", "repo", "uses", "speech", "css", "page"},
}


def test_vue_component_keeps_the_phase_on_the_svg_root() -> None:
    component = sync_badge.vue_component(REAL_SVG, "../assets/dictation-badge/badge.css")
    assert component.startswith("<!-- Generated by STT-Suite/scripts/sync_badge.py")
    assert 'import "../assets/dictation-badge/badge.css";' in component
    assert ":class=\"['dictation-badge', phase]\"" in component
    assert "xmlns" not in component
    assert component.count("<line ") == 5


def test_vue_component_refuses_a_root_without_the_class() -> None:
    with pytest.raises(ValueError, match="the root needs"):
        sync_badge.vue_component('<svg xmlns="http://www.w3.org/2000/svg"></svg>', "./badge.css")


def test_html_page_replaces_only_the_marked_part() -> None:
    page = f"<body>\n  {sync_badge.PAGE_BEGIN}\n  <svg>old</svg>\n  {sync_badge.PAGE_END}\n  <script></script>\n</body>\n"
    result = sync_badge.html_page(page, REAL_SVG, Path("badge.html"))
    assert "old" not in result
    assert result.startswith("<body>\n  " + sync_badge.PAGE_BEGIN + "\n  <svg ")
    assert result.endswith(sync_badge.PAGE_END + "\n  <script></script>\n</body>\n")
    assert sync_badge.html_page(result, REAL_SVG, Path("badge.html")) == result


def test_html_page_without_markers_is_an_error() -> None:
    with pytest.raises(ValueError, match="needs the markers"):
        sync_badge.html_page("<body></body>", REAL_SVG, Path("badge.html"))


def test_css_import_path_is_relative_to_the_component() -> None:
    css = Path("/r/frontend/src/assets/dictation-badge/badge.css")
    assert sync_badge.css_import_path(css, Path("/r/frontend/src/components/DictationBadge.vue")) == "../assets/dictation-badge/badge.css"
    assert sync_badge.css_import_path(css, Path("/r/frontend/src/assets/DictationBadge.vue")) == "./dictation-badge/badge.css"


def test_every_consumer_of_the_list_has_what_its_kind_needs() -> None:
    consumers = json.loads(sync_badge.CONSUMERS.read_text(encoding="utf-8"))["buttons"]
    assert {consumer["name"] for consumer in consumers} >= {"STT-Suite", "AIfred-Intelligence", "Agent-Orc", "Mundwerk", "AI-ATC"}
    for consumer in consumers:
        assert set(consumer) == KEYS_PER_KIND[consumer["kind"]], consumer["name"]
