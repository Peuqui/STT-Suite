"""The sync script that hands the shared pieces of the user interface (the dictation button, the speaker button) to the
programs (scripts/sync_ui.py)."""
import json
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "scripts"))
import render_badge_icons
import sync_ui

PIECES = sync_ui.pieces_of(sync_ui.load_list())
BADGE, SPEAKER = PIECES["badge"], PIECES["speaker"]
KEYS_PER_KIND = {
    "source": {"kind", "uses"},
    "vue": {"kind", "uses", "css", "component"},
    "html": {"kind", "uses", "css", "page"},
}
RASTER_KEYS = {"raster", "raster_stamp", "overview"}


def test_the_pieces_are_the_two_source_folders() -> None:
    assert set(PIECES) == {"badge", "speaker"}
    assert BADGE.label == "STT-Suite/ui/badge/" and BADGE.suite == "STT-Suite"
    assert SPEAKER.label == "TTS-Suite/src/tts_suite/service/ui/speaker/" and SPEAKER.suite == "TTS-Suite"
    assert set(sync_ui.COMPONENTS) == set(PIECES)


def test_the_badge_component_keeps_the_phase_on_the_svg_root() -> None:
    component = sync_ui.badge_component(BADGE, "../assets/dictation-badge/badge.css")
    assert component.startswith("<!-- Generated by STT-Suite/scripts/sync_ui.py from STT-Suite/ui/badge/")
    assert 'import "../assets/dictation-badge/badge.css";' in component
    assert ":class=\"['dictation-badge', phase]\"" in component
    assert "xmlns" not in component
    assert component.count("<line ") == 5


def test_the_speaker_component_has_the_props_and_the_arrow_only_on_from() -> None:
    component = sync_ui.speaker_component(SPEAKER, "../assets/speaker/speaker.css")
    assert component.startswith("<!-- Generated by STT-Suite/scripts/sync_ui.py from TTS-Suite/src/tts_suite/service/ui/speaker/")
    assert "change the source in the TTS-Suite." in component
    assert 'import "../assets/speaker/speaker.css";' in component
    assert "defineProps<{ from?: boolean; playing?: boolean }>();" in component
    assert '<span class="speaker" :class="{ playing }">' in component
    assert 'v-if="from" class="speaker-from"' in component
    assert "xmlns" not in component
    assert component.count("<line ") == 5


def test_a_component_refuses_a_source_without_what_it_needs(tmp_path: Path) -> None:
    (tmp_path / "badge.svg").write_text('<svg xmlns="http://www.w3.org/2000/svg"></svg>', encoding="utf-8")
    (tmp_path / "speaker.svg").write_text('<svg xmlns="http://www.w3.org/2000/svg"></svg>', encoding="utf-8")
    (tmp_path / "speaker-from.svg").write_text('<svg xmlns="http://www.w3.org/2000/svg"></svg>', encoding="utf-8")
    with pytest.raises(ValueError, match="the root needs"):
        sync_ui.badge_component(sync_ui.Piece("badge", tmp_path, "X/badge/"), "./badge.css")
    with pytest.raises(ValueError, match="speaker svg files"):
        sync_ui.speaker_component(sync_ui.Piece("speaker", tmp_path, "X/speaker/"), "./speaker.css")


def test_html_page_replaces_only_the_marked_part() -> None:
    begin, end = sync_ui.page_markers(BADGE)
    page = f"<body>\n  {begin}\n  <svg>old</svg>\n  {end}\n  <script></script>\n</body>\n"
    result = sync_ui.html_page(BADGE, page, Path("badge.html"))
    assert "old" not in result
    assert result.startswith("<body>\n  " + begin + "\n  <svg ")
    assert result.endswith(end + "\n  <script></script>\n</body>\n")
    assert sync_ui.html_page(BADGE, result, Path("badge.html")) == result


def test_html_page_finds_its_begin_marker_whatever_the_comment_says() -> None:
    _, end = sync_ui.page_markers(BADGE)
    page = f"<body>\n<!-- dictation-badge:begin (an older script name) -->\n<svg>old</svg>\n{end}\n</body>\n"
    assert "old" not in sync_ui.html_page(BADGE, page, Path("badge.html"))


def test_html_page_without_markers_is_an_error() -> None:
    with pytest.raises(ValueError, match="needs the markers"):
        sync_ui.html_page(BADGE, "<body></body>", Path("badge.html"))


def test_css_import_path_is_relative_to_the_component() -> None:
    css = Path("/r/frontend/src/assets/speaker/speaker.css")
    assert sync_ui.css_import_path(css, Path("/r/frontend/src/components/SpeakerIcon.vue")) == "../assets/speaker/speaker.css"
    assert sync_ui.css_import_path(css, Path("/r/frontend/src/assets/Icon.vue")) == "./speaker/speaker.css"


def test_every_program_of_the_list_has_what_its_kind_needs() -> None:
    data = sync_ui.load_list()
    programs = {program["name"]: program for program in data["programs"]}
    assert set(programs) >= {"STT-Suite", "TTS-Suite", "AIfred-Intelligence", "Agent-Orc", "Mundwerk", "AI-ATC"}
    for program in programs.values():
        assert {"name", "repo"} <= set(program)
        assert set(program) <= {"name", "repo", "speech", *PIECES}, program["name"]
        for piece in PIECES:
            block = program.get(piece)
            if block is None:
                continue
            assert set(block) - RASTER_KEYS == KEYS_PER_KIND[block["kind"]], f"{program['name']} {piece}"
            assert ("raster" in block) == ("raster_stamp" in block), program["name"]
            assert "raster" not in block or piece == "badge", program["name"]
            assert block["kind"] != "html" or piece in sync_ui.PAGE_MARKERS, program["name"]


def test_every_raster_file_has_a_known_state_and_a_size_where_it_needs_one() -> None:
    for program in json.loads(sync_ui.CONSUMERS.read_text(encoding="utf-8"))["programs"]:
        for entry in program.get("badge", {}).get("raster", []):
            assert entry["state"] in render_badge_icons.STATES, entry["file"]
            assert entry.get("profile", "default") in render_badge_icons.PROFILES, entry["file"]
            suffix = Path(entry["file"]).suffix
            assert suffix in {".png", ".ico", ".icns"}, entry["file"]
            assert ("size" in entry) == (suffix == ".png"), entry["file"]


def test_the_source_hash_follows_the_badge_files() -> None:
    assert render_badge_icons.source_hash() == render_badge_icons.source_hash()
    assert len(render_badge_icons.source_hash()) == 64
