"""Hands the dictation button of ui/badge/ to every program that shows it (the list: scripts/badge-consumers.json).

    python3 scripts/sync_badge.py          writes the copies
    python3 scripts/sync_badge.py --check  changes nothing; exit 1 where a copy differs from the source

Per kind of program:
  vue   badge.css is copied; DictationBadge.vue is made from badge.svg (prop `phase`, the svg's class follows it).
  html  badge.css is copied; the svg in the marked part of the page is replaced by badge.svg.
Nothing here is edited by hand in the programs: a change belongs in ui/badge/, then this runs again.
"""
import argparse
import json
import os
import re
import sys
from dataclasses import dataclass
from pathlib import Path

SUITE = Path(__file__).resolve().parent.parent
SOURCE = SUITE / "ui" / "badge"
CONSUMERS = Path(__file__).resolve().parent / "badge-consumers.json"
# The repos sit next to each other (the list gives their folder names).
REPOS = SUITE.parent

GENERATED = "Generated by STT-Suite/scripts/sync_badge.py from ui/badge/badge.svg: do not edit, change the source in the STT-Suite."
PAGE_MARKER = "dictation-badge"
PAGE_BEGIN = f"<!-- {PAGE_MARKER}:begin (from STT-Suite/ui/badge/badge.svg by scripts/sync_badge.py: do not edit) -->"
PAGE_END = f"<!-- {PAGE_MARKER}:end -->"
SVG_ROOT_CLASS = 'class="dictation-badge"'
SVG_NAMESPACE = ' xmlns="http://www.w3.org/2000/svg"'


@dataclass(frozen=True)
class Copy:
    """What a program should hold: its file and the content the source gives it."""
    path: Path
    content: str


def vue_component(svg: str, css_import: str) -> str:
    if SVG_ROOT_CLASS not in svg or SVG_NAMESPACE not in svg:
        raise ValueError(f"badge.svg: the root needs {SVG_ROOT_CLASS} and the namespace")
    template = svg.replace(SVG_NAMESPACE, "").replace(SVG_ROOT_CLASS, ':class="[\'dictation-badge\', phase]"')
    indented = "".join(f"  {line}\n" if line else "\n" for line in template.strip().splitlines())
    return (
        f"<!-- {GENERATED} -->\n"
        '<script setup lang="ts">\n'
        f'import "{css_import}";\n'
        'export type BadgePhase = "ready" | "listening" | "transcribing";\n'
        "defineProps<{ phase: BadgePhase }>();\n"
        "</script>\n\n"
        f"<template>\n{indented}</template>\n"
    )


def html_page(page: str, svg: str, page_path: Path) -> str:
    """The page with the part between the markers replaced by the svg (a page without markers is an error)."""
    # The begin marker is found by its name, whatever the comment after it says (it names this script).
    pattern = re.compile(rf"([ \t]*)<!-- {PAGE_MARKER}:begin.*?-->.*?{re.escape(PAGE_END)}", re.DOTALL)
    found = pattern.search(page)
    if found is None:
        raise ValueError(f"{page_path}: needs the markers {PAGE_BEGIN!r} and {PAGE_END!r} around the badge")
    indent = found.group(1)
    body = svg.replace(SVG_NAMESPACE, "").strip().splitlines()
    lines = [PAGE_BEGIN, *body, PAGE_END]
    return page[: found.start()] + "\n".join(f"{indent}{line}" if line else "" for line in lines) + page[found.end():]


def css_import_path(css: Path, component: Path) -> str:
    relative = os.path.relpath(css, component.parent)
    return relative if relative.startswith(".") else f"./{relative}"


def copies_for(consumer: dict[str, str]) -> list[Copy]:
    kind = consumer["kind"]
    if kind == "source":
        return []
    repo = REPOS / consumer["repo"]
    svg = (SOURCE / "badge.svg").read_text(encoding="utf-8")
    css_file = repo / consumer["css"]
    copies = [Copy(css_file, (SOURCE / "badge.css").read_text(encoding="utf-8"))]
    if kind == "vue":
        component = repo / consumer["component"]
        copies.append(Copy(component, vue_component(svg, css_import_path(css_file, component))))
    elif kind == "html":
        page = repo / consumer["page"]
        copies.append(Copy(page, html_page(page.read_text(encoding="utf-8"), svg, page)))
    else:
        raise ValueError(f"{consumer['name']}: unknown kind {kind!r}")
    return copies


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="change nothing; exit 1 where a copy differs")
    check_only = parser.parse_args().check
    consumers = json.loads(CONSUMERS.read_text(encoding="utf-8"))["buttons"]
    outdated = 0
    for consumer in consumers:
        for copy in copies_for(consumer):
            current = copy.path.read_text(encoding="utf-8") if copy.path.exists() else None
            if current == copy.content:
                continue
            outdated += 1
            print(f"{consumer['name']}: {copy.path.relative_to(REPOS)} {'differs' if check_only else 'written'}")
            if not check_only:
                copy.path.parent.mkdir(parents=True, exist_ok=True)
                copy.path.write_text(copy.content, encoding="utf-8")
    if outdated == 0:
        print("All copies are up to date.")
    return 1 if check_only and outdated else 0


if __name__ == "__main__":
    sys.exit(main())
