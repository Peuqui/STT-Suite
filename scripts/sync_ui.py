"""Hands the shared pieces of the user interface to every program that shows them (the list: scripts/ui-consumers.json).

A piece has one source folder, in the suite it belongs to, and is never edited anywhere else:
  badge    the dictation button (round badge, GPU mark, spinner)       STT-Suite/ui/badge/
  speaker  the speaker button (symbol, arrow for "from here on")       TTS-Suite/src/tts_suite/service/ui/speaker/

    python3 scripts/sync_ui.py          writes the copies
    python3 scripts/sync_ui.py --check  changes nothing; exit 1 where a copy differs from its source

What a program gets of a piece depends on its kind in the list:
  vue   the css is copied; the component is made from the svg files (its props are the piece's: the badge has `phase`,
        the speaker `from` and `playing`).
  html  the css is copied; the svg in the marked part of the page is replaced (the badge only).
A program that needs the badge as picture files (a tray icon, a program icon) has a "raster" list: those are made by
render_badge_icons.py (they are pictures, so no bytes are compared); here only the stamp it writes is checked, so a changed
source shows as an icon set that is out of date.
Nothing here is edited by hand in the programs: a change belongs in the piece's source folder, then this runs again.
"""
import argparse
import json
import os
import re
import sys
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from render_badge_icons import source_hash

SUITE = Path(__file__).resolve().parent.parent
CONSUMERS = Path(__file__).resolve().parent / "ui-consumers.json"
# The repos sit next to each other (the list gives their folder names).
REPOS = SUITE.parent
SYNC_SCRIPT = "STT-Suite/scripts/sync_ui.py"
SVG_NAMESPACE = ' xmlns="http://www.w3.org/2000/svg"'
BADGE_ROOT_CLASS = 'class="dictation-badge"'
SPEAKER_FROM_CLASS = ' class="speaker-from"'
# The name of the markers around a piece in an html page (only the badge can sit in a page).
PAGE_MARKERS = {"badge": "dictation-badge"}


@dataclass(frozen=True)
class Piece:
    """A shared piece: its name, its source folder and how that folder is named in the notes (STT-Suite/ui/badge/)."""
    name: str
    folder: Path
    label: str

    @property
    def suite(self) -> str:
        return self.label.split("/")[0]

    def read(self, file: str) -> str:
        return (self.folder / file).read_text(encoding="utf-8")


@dataclass(frozen=True)
class Copy:
    """What a program should hold: its file and the content the source gives it."""
    path: Path
    content: str


def load_list() -> dict[str, Any]:
    data: dict[str, Any] = json.loads(CONSUMERS.read_text(encoding="utf-8"))
    return data


def pieces_of(data: dict[str, Any]) -> dict[str, Piece]:
    return {name: Piece(name, REPOS / source["folder"], f"{source['folder']}/") for name, source in data["sources"].items()}


def generated_note(piece: Piece) -> str:
    return f"Generated by {SYNC_SCRIPT} from {piece.label}: do not edit, change the source in the {piece.suite}."


def _indented(svg: str, spaces: int) -> str:
    return "".join(f"{' ' * spaces}{line}\n" if line else "\n" for line in svg.strip().splitlines())


def badge_component(piece: Piece, css_import: str) -> str:
    svg = piece.read("badge.svg")
    if BADGE_ROOT_CLASS not in svg or SVG_NAMESPACE not in svg:
        raise ValueError(f"badge.svg: the root needs {BADGE_ROOT_CLASS} and the namespace")
    template = svg.replace(SVG_NAMESPACE, "").replace(BADGE_ROOT_CLASS, ':class="[\'dictation-badge\', phase]"')
    return (
        f"<!-- {generated_note(piece)} -->\n"
        '<script setup lang="ts">\n'
        f'import "{css_import}";\n'
        'export type BadgePhase = "ready" | "listening" | "transcribing";\n'
        "defineProps<{ phase: BadgePhase }>();\n"
        "</script>\n\n"
        f"<template>\n{_indented(template, 2)}</template>\n"
    )


def speaker_component(piece: Piece, css_import: str) -> str:
    icon_svg, from_svg = piece.read("speaker.svg"), piece.read("speaker-from.svg")
    if SVG_NAMESPACE not in icon_svg or SVG_NAMESPACE not in from_svg or SPEAKER_FROM_CLASS not in from_svg:
        raise ValueError(f"speaker svg files: the roots need the namespace, and speaker-from.svg {SPEAKER_FROM_CLASS.strip()}")
    icon = icon_svg.replace(SVG_NAMESPACE, "")
    arrow = from_svg.replace(SVG_NAMESPACE, "").replace(SPEAKER_FROM_CLASS, f' v-if="from"{SPEAKER_FROM_CLASS}')
    return (
        f"<!-- {generated_note(piece)} -->\n"
        '<script setup lang="ts">\n'
        f'import "{css_import}";\n'
        "defineProps<{ from?: boolean; playing?: boolean }>();\n"
        "</script>\n\n"
        "<template>\n"
        '  <span class="speaker" :class="{ playing }">\n'
        f"{_indented(icon, 4)}{_indented(arrow, 4)}"
        "  </span>\n"
        "</template>\n"
    )


# What makes the component of a piece (the props and the markup differ, everything else here is the same for all pieces).
COMPONENTS: dict[str, Callable[[Piece, str], str]] = {"badge": badge_component, "speaker": speaker_component}


def page_markers(piece: Piece) -> tuple[str, str]:
    name = PAGE_MARKERS[piece.name]
    return f"<!-- {name}:begin (from {piece.label} by {SYNC_SCRIPT}: do not edit) -->", f"<!-- {name}:end -->"


def html_page(piece: Piece, page: str, page_path: Path) -> str:
    """The page with the part between the markers replaced by the piece's svg (a page without markers is an error)."""
    begin, end = page_markers(piece)
    # The begin marker is found by its name, whatever the comment after it says (it names the script).
    pattern = re.compile(rf"([ \t]*)<!-- {PAGE_MARKERS[piece.name]}:begin.*?-->.*?{re.escape(end)}", re.DOTALL)
    found = pattern.search(page)
    if found is None:
        raise ValueError(f"{page_path}: needs the markers {begin!r} and {end!r} around the {piece.name}")
    indent = found.group(1)
    body = piece.read(f"{piece.name}.svg").replace(SVG_NAMESPACE, "").strip().splitlines()
    lines = [begin, *body, end]
    return page[: found.start()] + "\n".join(f"{indent}{line}" if line else "" for line in lines) + page[found.end():]


def css_import_path(css: Path, component: Path) -> str:
    relative = os.path.relpath(css, component.parent)
    return relative if relative.startswith(".") else f"./{relative}"


def copies_for(program: dict[str, Any], piece: Piece, block: dict[str, Any]) -> list[Copy]:
    kind = block["kind"]
    if kind == "source":
        return []
    repo = REPOS / program["repo"]
    css_file = repo / block["css"]
    copies = [Copy(css_file, piece.read(f"{piece.name}.css"))]
    if kind == "vue":
        component = repo / block["component"]
        copies.append(Copy(component, COMPONENTS[piece.name](piece, css_import_path(css_file, component))))
    elif kind == "html":
        page = repo / block["page"]
        copies.append(Copy(page, html_page(piece, page.read_text(encoding="utf-8"), page)))
    else:
        raise ValueError(f"{program['name']} ({piece.name}): unknown kind {kind!r}")
    return copies


def raster_outdated(program: dict[str, Any], block: dict[str, Any]) -> bool:
    """Whether the icons of a program were made from another source than the one now (or not at all)."""
    stamp = REPOS / program["repo"] / block["raster_stamp"]
    return not stamp.exists() or stamp.read_text(encoding="utf-8").strip() != source_hash()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="change nothing; exit 1 where a copy differs")
    check_only = parser.parse_args().check
    data = load_list()
    pieces = pieces_of(data)
    outdated = 0
    for program in data["programs"]:
        for name, piece in pieces.items():
            block = program.get(name)
            if block is None:
                continue
            for copy in copies_for(program, piece, block):
                current = copy.path.read_text(encoding="utf-8") if copy.path.exists() else None
                if current == copy.content:
                    continue
                outdated += 1
                print(f"{program['name']}: {copy.path.relative_to(REPOS)} {'differs' if check_only else 'written'}")
                if not check_only:
                    copy.path.parent.mkdir(parents=True, exist_ok=True)
                    copy.path.write_text(copy.content, encoding="utf-8")
            if "raster" in block and raster_outdated(program, block):
                outdated += 1
                print(f"{program['name']}: the icons are out of date, run scripts/render_badge_icons.py")
    if outdated == 0:
        print("All copies are up to date.")
    return 1 if check_only and outdated else 0


if __name__ == "__main__":
    sys.exit(main())
